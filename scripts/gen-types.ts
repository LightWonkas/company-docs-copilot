// Regenerates src/lib/supabase/database.types.ts from the local schema.
// CLI v3 prints status lines on stdout before the TypeScript, so keep only
// the generated code.
import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const OUT = "src/lib/supabase/database.types.ts";
const raw = execSync("pnpm exec supabase gen types typescript", { encoding: "utf8" });
const start = raw.indexOf("export type Json");
if (start < 0) throw new Error("unexpected `supabase gen types` output");
writeFileSync(OUT, `// Generated by \`pnpm db:types\`. Do not edit.\n${raw.slice(start)}`);
console.log(`Wrote ${OUT}`);
